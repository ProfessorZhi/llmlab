/*! tests/web-features/ops-bff-payload.test.js — the browser checks the *server's* output.
 *
 *  Every other test in this directory drives the in-process fixture. This one
 *  takes payloads produced by the real Python BFF — through a real login and a
 *  real `GET /api/v2/ops`, committed byte-for-byte at
 *  `tests/web-features/fixtures/bff-ops-payloads.json` — and puts them through
 *  the same `validateOps` and the same renderer the browser uses.
 *
 *  That is the only check that can catch the failure this whole layer exists to
 *  prevent: a server that is internally consistent but speaks a shape the
 *  front end refuses. If the two sides ever disagree, the panel goes blank in
 *  production and every test on either side still passes. Here it fails.
 *
 *  The fixture is regenerated by `python3 tests/bff/make_golden.py`, and a
 *  Python test asserts regeneration is a no-op.
 */

import test from 'node:test';
import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

import { validateOps, stateFor, OPS_STATES } from '../../web/js/features/contract.js';
import { deriveCapabilities } from '../../web/js/features/capability.js';
import { renderPanels } from '../../web/js/features/render.js';

const FIXTURE = JSON.parse(
  readFileSync(
    fileURLToPath(new URL('./fixtures/bff-ops-payloads.json', import.meta.url)),
    'utf8',
  ),
);

/** Validate + derive + render exactly as the controller does for a live payload. */
function paint(ops, { writable = true, visibility } = {}) {
  const checked = validateOps(ops);
  assert.equal(
    checked.ok,
    true,
    `the BFF payload was rejected: ${JSON.stringify(checked.errors)}`,
  );
  const capabilities = deriveCapabilities({ scopes: checked.ops.scope.scopes });
  const panels = renderPanels(checked.ops, capabilities, {
    visibility: visibility ?? checked.ops.scope.visibility,
    trendScope: 'mine',
    writable,
    error: null,
  });
  return { ops: checked.ops, capabilities, panels, html: Object.values(panels).join('\n') };
}

// --- the shape itself ---------------------------------------------------------

test('all three BFF payloads pass the browser contract', () => {
  for (const [name, ops] of Object.entries(FIXTURE)) {
    const checked = validateOps(ops);
    assert.deepEqual(checked.errors, [], `${name} was refused`);
    assert.equal(checked.ok, true, name);
    assert.equal(stateFor(checked.ops), OPS_STATES.READY, name);
  }
});

test('the payload is honest about being a synthetic build', () => {
  for (const ops of Object.values(FIXTURE)) {
    assert.equal(ops.synthetic, true);
    assert.equal(ops.transport.mode, 'demo');
    assert.notEqual(ops.transport.mode, 'live');
    assert.ok(ops.notes.length > 0);
  }
});

// --- what each viewer sees ----------------------------------------------------

test('the owner sees the deployment they registered', () => {
  const { panels } = paint(FIXTURE.member_private);
  assert.match(panels.registry, /我拥有的部署/);
  assert.match(panels.registry, /model-alice/);
});

test('the grantee sees the endpoint shared to them, and nothing of their own', () => {
  const { ops, panels } = paint(FIXTURE.grantee_shared);
  assert.equal(ops.registry.owned.length, 0);
  assert.equal(ops.registry.shared.length, 1);
  assert.equal(ops.registry.shared[0].owner_is_self, false);
  assert.match(panels.registry, /endpoint-alice/);
});

test('the administrator gets the deployment-wide view and a member does not', () => {
  const admin = paint(FIXTURE.admin_private);
  assert.equal(admin.capabilities.viewAllPrincipals.granted, true);
  assert.equal(admin.ops.admin.available, true);
  assert.equal(admin.ops.registry.all.length, 1);

  const member = paint(FIXTURE.member_private);
  assert.equal(member.capabilities.viewAllPrincipals.granted, false);
  assert.equal(member.ops.admin.available, false);
  assert.deepEqual(member.ops.registry.all, []);
  assert.doesNotMatch(member.html, /远端|全部部署数据来自/);
});

test('the share control is live for the owner and dead for the grantee', () => {
  const owner = paint(FIXTURE.member_private);
  const ownerButtons = owner.html.match(/<button[^>]*data-share-mode[^>]*>/g) ?? [];
  assert.ok(ownerButtons.length >= 3, 'the owner has no share control');
  for (const button of ownerButtons) assert.doesNotMatch(button, /\bdisabled\b/);

  const grantee = paint(FIXTURE.grantee_shared);
  const granteeButtons = grantee.html.match(/<button[^>]*data-share-mode[^>]*>/g) ?? [];
  for (const button of granteeButtons) assert.match(button, /\bdisabled\b/);
});

// --- the two rules that would make the page lie -------------------------------

test('no panel claims a GPU measurement', () => {
  for (const ops of Object.values(FIXTURE)) {
    const { html } = paint(ops);
    // No VRAM figure anywhere, and every metric card the server sent reads
    // UNKNOWN with the reason the server actually gave.
    assert.doesNotMatch(html, /\d+\s*MiB/);
    for (const metric of ops.metrics.items) {
      assert.equal(metric.value, null, metric.name);
      assert.equal(metric.state, 'unknown', metric.name);
      assert.ok(metric.reason, metric.name);
    }
    assert.match(html, /没有已声明的可信数据来源/);
  }
});

test('the host-scoped viewer gets device cards, and they are UNKNOWN too', () => {
  // Device readings are host-wide by construction — there is no per-principal
  // VRAM metric in the catalogue at all.
  const admin = paint(FIXTURE.admin_private);
  const deviceNames = admin.ops.metrics.items
    .map((metric) => metric.name)
    .filter((name) => name.startsWith('device.gpu'));
  assert.ok(deviceNames.length > 0, 'the admin payload has no device readings');
  for (const name of deviceNames) {
    assert.match(admin.html, new RegExp(`data-metric="${name.replace(/\./g, '\\.')}"`));
  }

  const member = paint(FIXTURE.member_private);
  for (const metric of member.ops.metrics.items) {
    assert.doesNotMatch(metric.name, /^(device|node)\./, metric.name);
    assert.doesNotMatch(metric.name, /gpu/i, metric.name);
  }
});

test('no panel names the upstream port or an absolute address', () => {
  for (const ops of Object.values(FIXTURE)) {
    const { html } = paint(ops);
    assert.doesNotMatch(html, /:8080/);
    assert.doesNotMatch(html, /href="https?:/);
    assert.doesNotMatch(html, /href="\/\//);
  }
});

test('the two controls that must never act stay disabled for every viewer', () => {
  for (const ops of Object.values(FIXTURE)) {
    const { html } = paint(ops);
    assert.match(html, /data-playground-send="1"[^>]*disabled/);
    assert.match(html, /data-eval-submit="1"[^>]*disabled/);
  }
});

test('an eval score never appears for a run that has not finished', () => {
  for (const ops of Object.values(FIXTURE)) {
    for (const run of ops.evaluation.runs) {
      if (run.status !== 'done') assert.equal(run.metric, null, run.run_id);
    }
  }
});

// --- the key table ------------------------------------------------------------

test('no key material is present, and any prefix shown is masked', () => {
  const blob = JSON.stringify(FIXTURE);
  assert.doesNotMatch(blob, /"secret"|"plaintext"|"token":\s*"/);
  for (const ops of Object.values(FIXTURE)) {
    for (const key of ops.keys) {
      assert.match(key.prefix, /[•*·]/);
      assert.ok(key.prefix.length <= 24);
    }
  }
});
