/*! web/js/features/mock-fixture.js — the offline `portal-ops/1` HTTP fixture.
 *
 *  This is the **front-end adapter's test double**, and it is a real HTTP-shaped
 *  fixture rather than a blob of constants: it speaks `fetch(url, init)` and
 *  answers `GET /api/v2/ops` and `PUT /api/v2/ops/deployments/:id/share` with
 *  status codes. That matters because it is what makes the share control
 *  *demonstrably functional* — the button performs a request, the fixture
 *  mutates in-memory state, the view re-reads and the new state is on screen.
 *  A button whose "function" is a hard-coded re-render proves nothing.
 *
 *  What it deliberately is not:
 *
 *  * **Not a production backend.** `backend/registry`, `backend/observability`,
 *    `backend/evaluation` and `backend/auth_linux` are being built on separate
 *    branches and none is merged. The paths below (`/api/v2/ops`) are the shape
 *    the browser adapter *proposes*; no server answers them today. The payload
 *    that comes out of here is `synthetic: true` and the UI must badge it.
 *  * **Not a GPU source.** Every GPU cell is `null` with a reason. This file
 *    contains no VRAM figure at all — grep it. The NVML rule is enforced in
 *    `contract.js`, but the cheapest way to never show a fake GPU number is to
 *    never write one down.
 *  * **Not a content store.** No prompt, completion or message text exists in
 *    this fixture, so none can leak into a management view.
 *
 *  Identities are synthetic (`demo-user-a`, …) and are **not** anyone's Linux
 *  account. Permissions come from the `scopes` list on each persona, never from
 *  the persona's name — see `capability.js`.
 *
 *  Everything is deterministic: the trend series is generated by a seeded
 *  generator, not `Math.random`, so a test can assert an exact rendered point
 *  and get the same answer twice.
 *
 *  No DOM, no network: unit-testable under plain Node.
 */

