/** A seeded 32-bit LCG. Deterministic by construction: `Math.random()` would
 *  make the rendered curve untestable. */
function seeded(seed) {
  let state = seed >>> 0;
  return () => {
    state = (state * 1664525 + 1013904223) >>> 0;
    return state / 0x100000000;
  };
}

/**
 * A 24-point synthetic series. Point 7 is a deliberate `null` — a gap in the
 * record. The renderer must draw it as a break, not as zero; that is a claim
 * this fixture exists to make testable.
 */
export function syntheticSeries({ seed, base, spread, unit, name, kind, scope }) {
  const rand = seeded(seed);
  const points = [];
  for (let i = 0; i < 24; i += 1) {
    points.push(i === 7 ? null : Math.round(base + (rand() - 0.5) * spread));
  }
  return { name, kind, scope, unit, points };
}

