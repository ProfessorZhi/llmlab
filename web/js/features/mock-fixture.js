const jsonResponse = (status, body) => ({
  ok: status >= 200 && status < 300,
  status,
  headers: { get: (name) => (String(name).toLowerCase() === 'content-type' ? 'application/json' : null) },
  json: async () => body,
});

const errorResponse = (status, code, message) =>
  jsonResponse(status, { error: { code, message } });

/** A same-origin path only. An absolute or protocol-relative URL would mean the
 *  fixture was being pointed at a real host, which is exactly what the adapter
 *  forbids — so it is refused here too, not just at the call site. */
function parsePath(url) {
  const raw = String(url ?? '');
  if (!raw.startsWith('/') || raw.startsWith('//') || raw.includes('://')) return null;
  const [path, query = ''] = raw.split('?');
  return { path, params: new URLSearchParams(query) };
}

function checkShareBody(body, errors) {
  if (!body || typeof body !== 'object' || Array.isArray(body)) {
    errors.push('body must be an object');
    return null;
  }
  if (!Object.values(SHARE_MODES).includes(body.mode)) {
    errors.push(`unsupported share mode: ${String(body.mode)}`);
    return null;
  }
  const principals = body.principals ?? [];
  if (!Array.isArray(principals) || principals.some((p) => typeof p !== 'string' || !p.trim())) {
    errors.push('principals must be a list of non-empty strings');
    return null;
  }
  if (body.mode === SHARE_MODES.SELECTED && !principals.length) {
    errors.push('mode "selected" needs at least one principal');
    return null;
  }
  return { mode: body.mode, principals: [...principals] };
}

/**
 * Build the fixture. Returns a `fetch`-shaped function plus the state it owns.
 *
 * @param {object} [options]
 * @param {string} [options.persona]  one of {@link PERSONA_NAMES}
 * @param {(url: string) => Promise<any>} [options.fetchImpl]  unused by the
 *        fixture itself; accepted so a caller can pass one uniformly and prove
 *        no ambient fetch is ever resolved in mock mode.
 */
export function createMockHttp({ persona = 'user', visibility = VISIBILITY.PRIVATE } = {}) {
  const state = createMockState({ persona, visibility });

  async function fetchImpl(url, init = {}) {
    const method = String(init.method ?? 'GET').toUpperCase();
    const parsed = parsePath(url);
    if (!parsed) {
      return errorResponse(400, 'invalid_request', 'the fixture only answers same-origin paths');
    }

    if (!state.session.subject) {
      return errorResponse(401, 'not_authenticated', 'no session');
    }

    if (parsed.path === OPS_ENDPOINT && method === 'GET') {
      // An absent parameter means the default, which is `private` — not "keep
      // whatever the last caller asked for". Without this the fixture leaks a
      // previously-selected `shared` view into a later private request.
      const requested = parsed.params.get('visibility') ?? VISIBILITY.PRIVATE;
      if (!Object.values(VISIBILITY).includes(requested)) {
        return errorResponse(400, 'invalid_request', `unknown visibility: ${requested}`);
      }
      state.visibility = requested;
      return jsonResponse(200, { data: { ops: buildOps(state) } });
    }

    const shareMatch = parsed.path.match(/^\/api\/v2\/ops\/deployments\/([^/]+)\/share$/);
    if (shareMatch && method === 'PUT') {
      if (!state.session.scopes.includes(SCOPES.ENDPOINTS_SHARE)) {
        return errorResponse(403, 'forbidden', `missing ${SCOPES.ENDPOINTS_SHARE}`);
      }
      const deploymentId = decodeURIComponent(shareMatch[1]);
      const deployment = state.registry.owned.find((d) => d.deployment_id === deploymentId);
      if (!deployment) {
        return errorResponse(404, 'not_found', `no such deployment: ${deploymentId}`);
      }
      if (!deployment.owner_is_self || deployment.owner_uid !== state.session.subject) {
        return errorResponse(403, 'forbidden', 'only the owner may change a share scope');
      }
      let body;
      try {
        body = typeof init.body === 'string' ? JSON.parse(init.body) : init.body;
      } catch {
        return errorResponse(400, 'invalid_request', 'body is not JSON');
      }
      const errors = [];
      const next = checkShareBody(body, errors);
      if (!next) return errorResponse(400, 'invalid_request', errors.join('; '));

      // Publishing is reversible by construction: going back to `private`
      // clears the principal list rather than leaving it to rot.
      deployment.share = {
        mode: next.mode,
        principals: next.mode === SHARE_MODES.PRIVATE ? [] : next.principals,
        revocable: true,
      };
      state.audit.push({
        at: 'synthetic', deployment_id: deploymentId, by: state.session.subject,
        from: null, to: deployment.share.mode, principals: [...deployment.share.principals],
      });
      return jsonResponse(200, { data: { deployment: { ...deployment } } });
    }

    return errorResponse(404, 'not_found', `no route for ${method} ${parsed.path}`);
  }

  return {
    persona,
    fetch: fetchImpl,
    /** Current state, deep-copied so a test cannot mutate the fixture by
     *  holding on to the snapshot. */
    snapshot: () => JSON.parse(JSON.stringify({
      session: state.session,
      visibility: state.visibility,
      registry: state.registry,
      audit: state.audit,
    })),
    ops: () => buildOps(state),
  };
}
