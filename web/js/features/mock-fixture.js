/**
 * The in-memory state a fixture instance owns. Exported so a test can build a
 * payload directly without going through HTTP, while the HTTP path stays the
 * one the UI uses.
 */
export function createMockState({ persona = 'user', visibility = VISIBILITY.PRIVATE } = {}) {
  const record = PERSONAS[persona];
  if (!record) throw new Error(`unknown persona: ${persona}`);
  if (!Object.values(VISIBILITY).includes(visibility)) {
    throw new Error(`unknown visibility: ${visibility}`);
  }
  const registry = seedDeployments();
  return {
    persona,
    session: {
      subject: record.subject,
      roles: [...record.roles],
      scopes: [...record.scopes],
    },
    registry: {
      // `principal` on every seeded row belongs to this persona; the shared row
      // belongs to someone else. The fixture therefore cannot accidentally hand
      // a caller a "mine" list containing a stranger's row.
      ...registry,
      owned: registry.owned.map((dep) => ({ ...dep, owner_uid: record.subject })),
    },
    visibility,
    /** Audit trail of accepted writes. In-process only; never persisted. */
    audit: [],
  };
}

